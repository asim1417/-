const PERSONAL_MED = [
  /عندي|أعاني|صار لي|ابني|زوجت|والدت|مريض(ي|تي)?\b/, // ضمير شخصي مرضي
  /شخّص|تشخيص|جرعة|كم آخذ|هل آخذ|علاج(ي)?\b|وصفة|دواء يناسب/,
  /نتيجة تحليل(ي)?|تحليلي|فحصي|أشعتي|تقريري الطبي/,
  /diagnos|prescri|what dose|should i take|my (symptom|result|test|lab)/i,
];

export function personalMedicalRequest(text: string): boolean {
  return PERSONAL_MED.some((r) => r.test(text));
}

